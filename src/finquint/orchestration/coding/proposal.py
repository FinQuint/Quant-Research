"""Host-built changes (ADR-023): the coding agent sends a module name and its source; the host
writes the paths, the registration file and the unified diff, so every touched path comes from here.

    module_path(name)             src/finquint/strategies/<name>.py
    render_registry(modules)      the full text of src/finquint/strategies/agent_templates.py
    registered_modules(text)      the modules a registry text imports (fails on a hand-edited file)
    build_change(name, source, registry_text) -> Change(files, patch, diff_sha, paths)
"""
import ast
from dataclasses import dataclass
import difflib
from hashlib import sha256
import re

STRATEGIES_DIR = "src/finquint/strategies"
REGISTRY_PATH = f"{STRATEGIES_DIR}/agent_templates.py"
MODULE_NAME = re.compile(r"^[a-z][a-z0-9_]{2,39}$")
RESERVED_MODULES = frozenset({"base", "agent_templates", "momentum", "__init__", "__main__"})

REGISTRY_HEADER = '''"""Agent-written strategy templates (Phase 10, ADR-023). Generated by the host; do not edit by hand.

The coding agent writes one new module per template; the host rewrites this file to import its
TEMPLATE. A change here arrives only through a reviewed PR on an agent/* branch, merged by a human.
"""
'''


class RegistryError(ValueError):
    """The registration file is not what the host would have written."""


def module_path(name):
    return f"{STRATEGIES_DIR}/{name}.py"


def render_registry(modules):
    modules = sorted(set(modules))
    if not modules:
        return REGISTRY_HEADER + "\nAGENT_TEMPLATES = ()\n"
    imports = "".join(f"from .{m} import TEMPLATE as _{m}\n" for m in modules)
    return REGISTRY_HEADER + "\n" + imports + "\nAGENT_TEMPLATES = (" + ", ".join(f"_{m}" for m in modules) + ",)\n"


def registered_modules(text):
    """Modules the registry imports. Raises RegistryError unless the text is exactly what
    render_registry() writes for them (a hand edit fails closed)."""
    try:
        tree = ast.parse(text)
    except SyntaxError as exc:
        raise RegistryError(f"registry does not parse: {exc}") from None
    modules = [n.module for n in tree.body if isinstance(n, ast.ImportFrom) and n.level == 1 and n.module]
    if normalize(text) != render_registry(modules):
        raise RegistryError("agent_templates.py differs from the host-written form")
    return tuple(sorted(modules))


def normalize(source):
    """LF line endings, exactly one trailing newline."""
    return source.replace("\r\n", "\n").replace("\r", "\n").rstrip("\n") + "\n"


@dataclass(frozen=True)
class Change:
    files: dict          # repo-relative path -> new full text
    patch: str
    diff_sha: str
    paths: tuple


def _new_file_diff(path, text):
    lines = text.splitlines(keepends=True)
    body = "".join("+" + line for line in lines)
    return (f"diff --git a/{path} b/{path}\nnew file mode 100644\n--- /dev/null\n+++ b/{path}\n"
            f"@@ -0,0 +1,{len(lines)} @@\n{body}")


def _modified_diff(path, before, after):
    diff = "".join(difflib.unified_diff(before.splitlines(keepends=True), after.splitlines(keepends=True),
                                        fromfile=f"a/{path}", tofile=f"b/{path}"))
    return f"diff --git a/{path} b/{path}\n{diff}" if diff else ""


def build_change(name, source, registry_text):
    """The change for one new template module. Raises RegistryError on a hand-edited registry."""
    modules = registered_modules(registry_text)
    source = normalize(source)
    path = module_path(name)
    registry = render_registry((*modules, name))
    patch = _new_file_diff(path, source) + _modified_diff(REGISTRY_PATH, normalize(registry_text), registry)
    return Change({path: source, REGISTRY_PATH: registry}, patch, sha256(patch.encode("utf-8")).hexdigest(),
                  tuple(sorted((path, REGISTRY_PATH))))


__all__ = ["Change", "MODULE_NAME", "REGISTRY_PATH", "RESERVED_MODULES", "RegistryError", "STRATEGIES_DIR",
           "build_change", "module_path", "normalize", "registered_modules", "render_registry"]
